ALTER TABLE payments ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
-- Historical rows without an order reference are uncertain, never safe to
-- resubmit. Only new application-created rows start as NOT_STARTED.
ALTER TABLE payments ADD COLUMN gateway_order_state VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN';
ALTER TABLE payments ADD COLUMN gateway_submitted_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE payments ADD COLUMN next_recovery_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE payments ADD COLUMN recovery_attempts INTEGER NOT NULL DEFAULT 0;

UPDATE payments SET gateway_order_state = 'READY' WHERE provider_reference_id IS NOT NULL;
UPDATE payments SET next_recovery_at = CURRENT_TIMESTAMP
    WHERE provider = 'RAZORPAY' AND status NOT IN ('SUCCESS', 'REFUNDED');

-- If historical duplicate provider references exist, fail migration rather
-- than silently deciding which financial record owns that provider order.
CREATE UNIQUE INDEX uk_payment_provider_reference ON payments(provider, provider_reference_id);
CREATE INDEX idx_payment_booking ON payments(booking_id);
CREATE INDEX idx_payment_user_created ON payments(user_id, created_at);
CREATE INDEX idx_payment_recovery ON payments(next_recovery_at);

CREATE TABLE payment_windows (
    booking_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    payment_id VARCHAR(40) UNIQUE REFERENCES payments(payment_id)
);

CREATE TABLE payment_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    booking_id BIGINT NOT NULL,
    payment_id BIGINT NOT NULL REFERENCES payments(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payment_request_user_key UNIQUE(user_id, idempotency_key)
);
