-- Repair installations where V2 was recorded as applied but one of the
-- auxiliary idempotency tables was not created (for example after an
-- interrupted non-transactional DDL operation). On a healthy installation
-- these statements are no-ops.
CREATE TABLE IF NOT EXISTS payment_windows (
    booking_id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    payment_id VARCHAR(40) UNIQUE REFERENCES payments(payment_id)
);

CREATE TABLE IF NOT EXISTS payment_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    booking_id BIGINT NOT NULL,
    payment_id BIGINT NOT NULL REFERENCES payments(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payment_request_user_key UNIQUE(user_id, idempotency_key)
);
